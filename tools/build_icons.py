#!/usr/bin/env python3
"""Regenerate assets/icons/*.svg, scripts/ui/icon_set.luau and CREDITS_ICONS.md
from a game-icons.net checkout. Usage: build_icons.py <path-to-game-icons/icons clone>
Swap the whole set by editing ICONS below (one line per icon).
The engine decodes rasters only (stb_image), so every SVG is also rendered to a white 64x64 PNG (assets/icons/*.png,
needs rsvg-convert); the UI tints it with UiImage.color. `build_icons.py --png-only` redoes just the PNGs from the SVGs."""
import re, subprocess, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
PNG_SIZE = 64
def render_png(svg: pathlib.Path):
    white = svg.read_text().replace("currentColor", "#ffffff")
    subprocess.run(["rsvg-convert", "-w", str(PNG_SIZE), "-h", str(PNG_SIZE), "-o", str(svg.with_suffix(".png"))], input=white.encode(), check=True)
if sys.argv[1] == "--png-only":
    for svg in sorted((root/"assets/icons").glob("*.svg")): render_png(svg)
    sys.exit(0)
src = pathlib.Path(sys.argv[1])
AUTHORS = {"lorc": ("Lorc", "http://lorcblog.blogspot.com"), "delapouite": ("Delapouite", "http://delapouite.com")}
# kind, name, (author-folder, file)
ICONS = [
 ("resource","credits","delapouite/coins"), ("resource","titanium","lorc/metal-bar"),
 ("resource","cobalt","lorc/crystal-cluster"), ("resource","compute","lorc/processor"),
 ("resource","reputation","lorc/laurels"),
 ("tool","mine","lorc/mining"), ("tool","return","lorc/return-arrow"),
 ("tool","sell","delapouite/receive-money"), ("tool","report","delapouite/notebook"),
 ("tool","scan","lorc/radar-sweep"), ("tool","store","delapouite/cargo-crate"),
 ("tool","read_market","delapouite/chart"), ("tool","ship","delapouite/cargo-ship"),
 ("agent","miner","delapouite/mining-helmet"), ("agent","logistician","delapouite/delivery-drone"),
 ("agent","monitor","delapouite/eye-target"),
]
out = root/"assets/icons"; out.mkdir(parents=True, exist_ok=True)
lua = ["-- GENERATED by tools/build_icons.py - do not edit by hand.",
       "-- Single lookup: icon key -> file + author. Swapping the set = rerun the script / edit this table.",
       "-- Colors are NOT baked in: the PNGs are white (rendered from the currentColor SVGs); tint with theme.dim/theme.text (idle)",
       "-- or the neon from `active_color` (active). Glow only when active (see icon_style.luau).",
       "local IconSet = {}", "IconSet.icons = {"]
cred = ["# Icon credits", "", "Icons from [game-icons.net](https://game-icons.net), licensed CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).", "Colors/background modified (recolored, background removed). Generated by `tools/build_icons.py`.", "", "| Icon | Used as | Author | Source |", "|---|---|---|---|"]
for kind, name, ref in ICONS:
    folder, f = ref.split("/")
    s = (src/folder/f"{f}.svg").read_text()
    s = re.sub(r'<path d="M0 0h512v512H0z"/>', "", s)
    s = s.replace('fill="#fff"', 'fill="currentColor"')
    assert "currentColor" in s, ref
    (out/f"{kind}_{name}.svg").write_text(s)
    render_png(out/f"{kind}_{name}.svg")
    a, url = AUTHORS[folder]
    lua.append(f'\t["{kind}.{name}"] = {{ file = "icons/{kind}_{name}.png", author = "{a}", source = "https://game-icons.net/1x1/{folder}/{f}.html" }},')
    cred.append(f"| {f} | {kind}.{name} | {a} | https://game-icons.net/1x1/{folder}/{f}.html |")
lua += ["}", "", "return IconSet", ""]
(root/"scripts/ui").mkdir(parents=True, exist_ok=True)
(root/"scripts/ui/icon_set.luau").write_text("\n".join(lua))
(root/"CREDITS_ICONS.md").write_text("\n".join(cred)+"\n")
